fn main() {
    generate_icons();
    #[cfg(target_os = "windows")]
    compile_windows_resources();
}

fn generate_icons() {
    use std::fs;
    use std::path::Path;

    let icons_dir = Path::new("assets/icons");
    let out_path = Path::new(&std::env::var("OUT_DIR").unwrap()).join("icons_generated.rs");

    println!("cargo:rerun-if-changed=assets/icons");

    let mut entries: Vec<_> = fs::read_dir(icons_dir)
        .expect("assets/icons directory missing")
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().is_some_and(|ext| ext == "svg"))
        .collect();
    entries.sort_by_key(|e| e.file_name());

    let mut code = String::from(
        "// @generated by build.rs — do not edit\n\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n\
         pub enum IconName {\n",
    );

    for entry in &entries {
        let path = entry.path();
        let stem = path.file_stem().unwrap().to_string_lossy();
        let variant = to_pascal_case(&stem);
        code.push_str(&format!("    {variant},\n"));
    }

    code.push_str(
        "}\n\nimpl IconName {\n    pub fn path(self) -> &'static str {\n        match self {\n",
    );

    for entry in &entries {
        let path = entry.path();
        let stem = path.file_stem().unwrap().to_string_lossy();
        let variant = to_pascal_case(&stem);
        code.push_str(&format!(
            "            Self::{variant} => \"icons/{stem}.svg\",\n"
        ));
    }

    code.push_str("        }\n    }\n\n    pub fn all() -> &'static [IconName] {\n        &[\n");
    for entry in &entries {
        let path = entry.path();
        let stem = path.file_stem().unwrap().to_string_lossy();
        let variant = to_pascal_case(&stem);
        code.push_str(&format!("            IconName::{variant},\n"));
    }
    code.push_str("        ]\n    }\n}\n");

    fs::write(out_path, code).expect("write icons_generated.rs");
}

fn to_pascal_case(name: &str) -> String {
    name.split('-')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}

#[cfg(target_os = "windows")]
fn compile_windows_resources() {
    if std::path::Path::new("assets/icon.png").exists() {
        write_ico_from_png("assets/icon.png", "assets/icon.ico");
        let mut res = winres::WindowsResource::new();
        res.set_icon("assets/icon.ico");
        res.set("ProductName", "DeepSeekCode");
        res.set("FileDescription", "DeepSeekCode");
        res.set("InternalName", "deepseekcode");
        res.set("OriginalFilename", "deepseekcode.exe");
        if let Err(err) = res.compile() {
            eprintln!("winres: {err}");
        }
    }
}

#[cfg(target_os = "windows")]
fn write_ico_from_png(png_path: &str, ico_path: &str) {
    use std::fs::File;
    use std::io::BufWriter;

    let img = match image::open(png_path) {
        Ok(img) => img.into_rgba8(),
        Err(err) => {
            eprintln!("icon png: {err}");
            return;
        }
    };
    let (w, h) = img.dimensions();
    let icon_img = ico::IconImage::from_rgba_data(w, h, img.into_raw());
    let mut icon_dir = ico::IconDir::new(ico::ResourceType::Icon);
    let entry = match ico::IconDirEntry::encode(&icon_img) {
        Ok(entry) => entry,
        Err(err) => {
            eprintln!("icon encode: {err}");
            return;
        }
    };
    icon_dir.add_entry(entry);
    if let Ok(file) = File::create(ico_path) {
        let _ = icon_dir.write(BufWriter::new(file));
    }
}

#[cfg(not(target_os = "windows"))]
fn compile_windows_resources() {}
