fn main() {
    generate_icons();
    #[cfg(target_os = "windows")]
    compile_windows_resources();
}

fn generate_icons() {
    use std::fs;
    use std::path::Path;

    let icons_dir = Path::new("assets/icons");
    let out_path = Path::new(
        &std::env::var("OUT_DIR").expect("build.rs: OUT_DIR not set by Cargo"),
    )
    .join("icons_generated.rs");

    println!("cargo:rerun-if-changed=assets/icons");

    // P1-12: tolerant when `assets/icons` is absent (docs-only checkouts,
    // packaging without assets). Emit an empty enum instead of panicking.
    let Ok(read_dir) = fs::read_dir(icons_dir) else {
        println!("cargo:warning=assets/icons missing; generating empty IconName");
        fs::write(
            &out_path,
            "// @generated by build.rs — empty (assets/icons missing)\n\
             #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n\
             pub enum IconName {}\n\
             impl IconName { pub fn path(self) -> &'static str { \"\" } pub fn all() -> &'static [IconName] { &[] } }\n",
        )
        .ok();
        return;
    };
    let mut entries: Vec<_> = read_dir
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().is_some_and(|ext| ext == "svg"))
        .collect();
    entries.sort_by_key(|e| e.file_name());

    let mut code = String::from(
        "// @generated by build.rs — do not edit\n\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n\
         pub enum IconName {\n",
    );

    for entry in &entries {
        let path = entry.path();
        // Skip entries without a valid UTF-8 stem instead of panicking:
        // a stray file (e.g. `.DS_Store`, non-UTF8 name) must not break
        // the whole desktop build.
        let Some(stem_os) = path.file_stem() else {
            continue;
        };
        let stem = stem_os.to_string_lossy();
        let variant = to_pascal_case(&stem);
        code.push_str(&format!("    {variant},\n"));
    }

    code.push_str(
        "}\n\nimpl IconName {\n    pub fn path(self) -> &'static str {\n        match self {\n",
    );

    for entry in &entries {
        let path = entry.path();
        let Some(stem_os) = path.file_stem() else {
            continue;
        };
        let stem = stem_os.to_string_lossy();
        let variant = to_pascal_case(&stem);
        code.push_str(&format!(
            "            Self::{variant} => \"icons/{stem}.svg\",\n"
        ));
    }

    code.push_str("        }\n    }\n\n    pub fn all() -> &'static [IconName] {\n        &[\n");
    for entry in &entries {
        let path = entry.path();
        let Some(stem_os) = path.file_stem() else {
            continue;
        };
        let stem = stem_os.to_string_lossy();
        let variant = to_pascal_case(&stem);
        code.push_str(&format!("            IconName::{variant},\n"));
    }
    code.push_str("        ]\n    }\n}\n");

    // Build-script IO failure must fail the build loudly with context
    // (a silent `ok()` would generate a missing-symbols compile error later).
    if let Err(e) = fs::write(out_path, code) {
        panic!("build.rs: failed to write icons_generated.rs: {e}");
    }
}

fn to_pascal_case(name: &str) -> String {
    // P1-12: split on `-`, `_`, whitespace so all stems yield valid idents.
    // Non-alphanumeric runs are skipped; empty stems become `Icon`.
    let mut out = String::new();
    for part in name.split(|c| c == '-' || c == '_' || c == ' ' || c == '.') {
        let cleaned: String = part.chars().filter(|c| c.is_alphanumeric()).collect();
        if cleaned.is_empty() {
            continue;
        }
        let mut chars = cleaned.chars();
        if let Some(first) = chars.next() {
            out.push_str(&first.to_uppercase().collect::<String>());
            out.push_str(chars.as_str());
        }
    }
    if out.is_empty() {
        "Icon".to_string()
    } else {
        // Identifiers must not start with a digit.
        if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
            format!("Icon{out}")
        } else {
            out
        }
    }
}

#[cfg(target_os = "windows")]
fn compile_windows_resources() {
    if std::path::Path::new("assets/icon.png").exists() {
        // P1-12: write to OUT_DIR, never pollute the source tree (previously
        // overwrote `assets/icon.ico` on every build).
        let out_ico = std::path::Path::new(
            &std::env::var("OUT_DIR").expect("build.rs: OUT_DIR not set by Cargo"),
        )
        .join("icon.ico");
        write_ico_from_png("assets/icon.png", &out_ico.to_string_lossy());
        let mut res = winres::WindowsResource::new();
        res.set_icon(&out_ico.to_string_lossy());
        res.set("ProductName", "DeepSeekCode");
        res.set("FileDescription", "DeepSeekCode Desktop");
        res.set("InternalName", "deepseekcode-desktop");
        res.set("OriginalFilename", "deepseekcode-desktop.exe");
        if let Err(err) = res.compile() {
            eprintln!("winres: {err}");
        }
    }
}

#[cfg(target_os = "windows")]
fn write_ico_from_png(png_path: &str, ico_path: &str) {
    use std::fs::File;
    use std::io::BufWriter;

    let img = match image::open(png_path) {
        Ok(img) => img.into_rgba8(),
        Err(err) => {
            eprintln!("icon png: {err}");
            return;
        }
    };
    let (w, h) = img.dimensions();
    let icon_img = ico::IconImage::from_rgba_data(w, h, img.into_raw());
    let mut icon_dir = ico::IconDir::new(ico::ResourceType::Icon);
    let entry = match ico::IconDirEntry::encode(&icon_img) {
        Ok(entry) => entry,
        Err(err) => {
            eprintln!("icon encode: {err}");
            return;
        }
    };
    icon_dir.add_entry(entry);
    if let Ok(file) = File::create(ico_path) {
        let _ = icon_dir.write(BufWriter::new(file));
    }
}

#[cfg(not(target_os = "windows"))]
fn compile_windows_resources() {}
